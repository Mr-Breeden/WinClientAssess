def artifact(key: str) -> str:
    return ARTIFACTS[key]["filename"]

def generated_files() -> set[str]:
    return {spec["filename"] for spec in ARTIFACTS.values()}


def module_artifacts(module: str) -> tuple[str, ...]:
    """Return catalog filenames associated with an orchestration module."""
    return tuple(artifact(key) for key in MODULE_ARTIFACT_KEYS.get(module, ()))
